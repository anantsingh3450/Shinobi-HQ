"""A lock on the dashboard, because it is a trading control surface.

The dashboard has 89 routes and no authentication of any kind. Twenty-five of
them change state, and these are the ones that matter:

    POST /portfolio/<account_id>/trade      place a trade
    POST /positions/<symbol>/close          close any position
    POST /broker/token                      write the broker access token
    POST /commander/mode                    change execution mode
    POST /chat, /commander/chat             an LLM path that can trade, and
                                            which skips the risk gates entirely

On the laptop it binds 0.0.0.0:5000 behind a home router and nobody notices. On
a public server that is a stranger's trading terminal.

THE DESIGN, AND WHY IT IS SHAPED THIS WAY

1. LOOPBACK STAYS OPEN. A request genuinely originating on the machine needs no
   password. That keeps the laptop workflow and the `ssh -L 5000:...` tunnel
   working exactly as they do today — the commander can migrate and do his daily
   Kite login before any TLS or login page exists.

2. A FORWARDED REQUEST IS NEVER LOOPBACK. This is the trap. Put nginx or Caddy
   in front for TLS — which the migration runbook recommends — and every request
   arrives from 127.0.0.1. A naive loopback check would disable authentication
   completely at the exact moment the dashboard became public. So the presence
   of any X-Forwarded-For / X-Real-IP header disqualifies a request from the
   loopback exemption, regardless of the socket address.

3. IT FAILS CLOSED. A remote request with no password configured is REFUSED,
   not allowed. Exposing the dashboard before setting a password gets you a 503
   telling you how to set one — never an open terminal. The dangerous default
   must be the one that stops.

4. THE PASSWORD IS NEVER STORED, ONLY ITS HASH. `HOKAGE_DASHBOARD_PASSWORD_HASH`
   holds a PBKDF2 hash generated by tools/ops/set_dashboard_password.py, which
   the commander runs himself. Nothing here, and nobody helping him, needs to
   see the password itself.

5. FAILED ATTEMPTS ARE RATE LIMITED, per source address, with a lockout — a
   password worth having is worth not letting someone guess at machine speed.
"""
from __future__ import annotations

import hmac
import logging
import os
import time
from collections import defaultdict

logger = logging.getLogger("Hokage.DashboardAuth")

#: Environment variable holding the PBKDF2 hash (never the password).
PASSWORD_HASH_ENV = "HOKAGE_DASHBOARD_PASSWORD_HASH"

#: Optional. A stable value keeps sessions alive across restarts; without it a
#: random key is generated per process, which simply means re-logging in after
#: a deploy. That is a mild annoyance, never an insecurity.
SECRET_KEY_ENV = "HOKAGE_DASHBOARD_SECRET_KEY"

#: Paths reachable without a session, so the login page itself is usable.
PUBLIC_PATHS = frozenset({"/login", "/logout", "/healthz"})

#: Failed attempts from one address before it is locked out, and for how long.
MAX_ATTEMPTS = 5
LOCKOUT_SECONDS = 900

#: Headers that prove a request passed through a proxy. Their PRESENCE is what
#: matters — the value is attacker-controlled and is never trusted.
_PROXY_HEADERS = ("X-Forwarded-For", "X-Real-IP", "Forwarded", "X-Forwarded-Host")

_LOOPBACK = frozenset({"127.0.0.1", "::1", "localhost"})

#: address -> (failure count, first-failure timestamp)
_attempts: dict[str, list] = defaultdict(lambda: [0, 0.0])


def password_hash() -> str | None:
    value = (os.environ.get(PASSWORD_HASH_ENV) or "").strip()
    return value or None


def is_configured() -> bool:
    return password_hash() is not None


def is_local_request(remote_addr: str | None, headers) -> bool:
    """True only for a request that genuinely originated on this machine.

    A proxied request reports the proxy's address, so ANY forwarding header
    disqualifies the exemption. Without this, putting TLS in front of the
    dashboard would silently switch authentication off.
    """
    try:
        for header in _PROXY_HEADERS:
            if headers.get(header):
                return False
    except Exception:
        return False
    return (remote_addr or "") in _LOOPBACK


def check_password(candidate: str) -> bool:
    """Verify against the stored hash. False when nothing is configured."""
    stored = password_hash()
    if not stored or not candidate:
        return False
    try:
        from werkzeug.security import check_password_hash

        return bool(check_password_hash(stored, candidate))
    except Exception as exc:
        logger.error(f"Password check failed: {exc}")
        return False


def locked_out(addr: str) -> int:
    """Seconds remaining on a lockout, or 0."""
    count, first = _attempts.get(addr, [0, 0.0])
    if count < MAX_ATTEMPTS:
        return 0
    elapsed = time.time() - first
    if elapsed >= LOCKOUT_SECONDS:
        _attempts.pop(addr, None)
        return 0
    return int(LOCKOUT_SECONDS - elapsed)


def record_failure(addr: str) -> None:
    entry = _attempts[addr]
    if entry[0] == 0:
        entry[1] = time.time()
    entry[0] += 1
    if entry[0] >= MAX_ATTEMPTS:
        logger.warning(
            "Dashboard login locked out %s after %d failed attempts.",
            addr, entry[0],
        )


def clear_failures(addr: str) -> None:
    _attempts.pop(addr, None)


def reset_attempts() -> None:
    """Test seam. Never called in production."""
    _attempts.clear()


def session_secret() -> str:
    """Stable if configured, otherwise random per process."""
    configured = (os.environ.get(SECRET_KEY_ENV) or "").strip()
    if configured:
        return configured
    return os.urandom(32).hex()


def constant_time_equals(a: str, b: str) -> bool:
    return hmac.compare_digest((a or "").encode(), (b or "").encode())
